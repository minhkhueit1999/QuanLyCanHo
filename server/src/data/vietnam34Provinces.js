function buildWardLegacyAliases(adminCode, name) {
  const shortName = String(name).replace(/^(Phường|Xã|Đặc khu|Thị trấn)\s+/i, '').trim();
  const curated = CURATED_WARD_ALIASES[`${adminCode}:${name}`] || [];
  const merged = new Set([shortName, ...curated].filter(Boolean));
  return Array.from(merged);
}

